"""Exact close-only immutable fill/funding SQL, disposable PostgreSQL 16 only.

Never connect to production: requires CI, explicit ephemeral opt-in, loopback
host, local known credentials and no DATABASE_URL/MEXC keys. The dedicated
workflow starts the disposable database from scratch.
"""
from __future__ import annotations

from copy import deepcopy
from decimal import Decimal as D
import os
from pathlib import Path

import asyncpg
import pytest

from app.t100_live_fill_ledger import build_verified_order_fill_set
from app.t100_live_funding_ledger import build_verified_closed_position_funding_set
from app import t100_v40_close_financial_artifact_staging as stage
from tests.test_t100_v40_portfolio_close_financial_reader import order_and_deals
from tests.test_t100_live_funding_ledger import pages,row

ROOT=Path(__file__).resolve().parents[1]


@pytest.mark.asyncio
async def test_real_pg16_immutable_same_rows_and_rollback_of_conflict():
    env=os.environ
    if env.get("T100_V40_CLOSE_ARTIFACT_PG16_CI_ONLY")!="yes":
        pytest.skip("only the dedicated disposable PostgreSQL workflow")
    for key,required in (
        ("CI","true"),("PGHOST","127.0.0.1"),("PGPORT","5432"),
        ("PGDATABASE","mexc_exhaustion"),("PGUSER","postgres"),
        ("PGPASSWORD","t100-ci-only-local-postgres"),
        ("T100_EXECUTION_MODE","paper"),
        ("T100_LIVE_ORDER_API_ENABLED","false"),
        ("T100_LIVE_KILL_SWITCH","true"),
    ):
        assert env.get(key)==required
    assert not env.get("DATABASE_URL")
    assert not env.get("MEXC_API_KEY")
    assert not env.get("MEXC_API_SECRET")
    conn=await asyncpg.connect(
        host="127.0.0.1",port=5432,user="postgres",
        database="mexc_exhaustion",
        password="t100-ci-only-local-postgres",
        ssl=False,timeout=5,
    )
    try:
        for file in ("027_t100_live_order_intents.sql",
                     "029_t100_live_durable_state.sql"):
            await conn.execute((ROOT/"migrations"/file).read_text())
        first_order,first_deals=order_and_deals("100",3,100,2000)
        last_order,last_deals=order_and_deals("200",2,90,3000)
        original=build_verified_order_fill_set(
            order_id="100",order=first_order,fills=first_deals,
        )
        closing=build_verified_order_fill_set(
            order_id="200",order=last_order,fills=last_deals,
        )
        events=pages([row(1,settleTime=2500,
                         positionValue=100,funding=0.1,rate=0.001)])
        funding=build_verified_closed_position_funding_set(
            position_id="10",first=events,second=events,
        )

        async with conn.transaction(isolation="serializable"):
            await stage._persist_fill(conn,original)
            await stage._persist_fill(conn,closing)
            await stage._persist_funding(conn,funding)
        assert await conn.fetchval(
            "SELECT COUNT(*)::int FROM public.t100_live_order_fill_sets"
        )==2
        assert await conn.fetchval(
            "SELECT COUNT(*)::int FROM public.t100_live_order_fills"
        )==2
        assert await conn.fetchval(
            "SELECT COUNT(*)::int FROM public.t100_live_position_funding_sets"
        )==1
        assert await conn.fetchval(
            "SELECT COUNT(*)::int FROM public.t100_live_funding_events"
        )==1
        async with conn.transaction(isolation="serializable"):
            await stage._persist_fill(conn,original)
            await stage._persist_fill(conn,closing)
            await stage._persist_funding(conn,funding)

        # An existing row carrying a conflicting fee must never be
        # overwritten or silently accepted. Even a successful earlier
        # INSERT in the same TX must be rolled back with the conflict.
        await conn.execute(
            """UPDATE public.t100_live_order_fills SET fee_usdt=999
               WHERE order_id='100'"""
        )
        with pytest.raises(stage.V40CloseArtifactHalted,
                           match="FILL_ROW_IDENTITY_DRIFT"):
            async with conn.transaction(isolation="serializable"):
                await stage._persist_funding(conn,funding)
                await stage._persist_fill(conn,original)
        assert await conn.fetchval(
            "SELECT fee_usdt FROM public.t100_live_order_fills WHERE order_id='100'"
        )==D("999")
        # No final P&L or slot release is generated by this writer.
        assert await conn.fetchval(
            "SELECT COUNT(*)::int FROM public.t100_live_final_position_accounting"
        )==0
        assert await conn.fetchval(
            "SELECT COUNT(*)::int FROM public.t100_live_position_checkpoints"
        )==0
    finally:
        await conn.close()
